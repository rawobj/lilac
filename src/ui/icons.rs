//! Paths of the embedded icons, as `&'static str` so using one never allocates.

macro_rules! icon_paths {
    ($($ident:ident = $name:literal),* $(,)?) => {
        $(pub const $ident: &str = concat!("icons/", $name, ".svg");)*
    };
}

